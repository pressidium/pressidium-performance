/**
 * Cache_Tag_Manager class.
 *
 * @since 1.1.0
 */
class Cache_Tag_Manager {

    /**
     * @var string Cache tag header.
     */
    const CACHE_TAG_HEADER = 'Surrogate-Key';

    /**
     * @var Cache_Tag[] Cache tags.
     */
    private array $cache_tags = array();

    /**
     * @var string Web property handle.
     */
    private string $web_property_handle;

    /**
     * Cache_Tag_Manager constructor.
     *
     * @param Cache_Tag_Factory $cache_tag_factory `Cache_Tag_Factory` instance.
     * @param Web_Property      $web_property      `Web_Property` instance.
     */
    public function __construct( private readonly Cache_Tag_Factory $cache_tag_factory, Web_Property $web_property ) {
        $this->web_property_handle = $web_property->get_web_property_handle();

        $this->compute_all_cache_tags();
    }

    /**
     * Compute all cache tags.
     *
     * @return void
     */
    private function compute_all_cache_tags(): void {
        /*
         * Mapping of cache tags to condition functions.
         * The key is the cache tag name, and the value is the condition function.
         */
        $mapping = array(
            Cache_Tag::AUTHOR    => 'is_author',
            Cache_Tag::TAXONOMY  => 'is_any_taxonomy',
            Cache_Tag::POST_TYPE => 'is_post_type_archive',
            Cache_Tag::DATE      => 'is_date',
            Cache_Tag::SITEMAP   => 'is_sitemap',
            Cache_Tag::FEED      => 'is_feed',
            Cache_Tag::REST      => 'is_rest',
            Cache_Tag::SEARCH    => 'is_search',
            Cache_Tag::FRONT     => 'is_front_page',
            Cache_Tag::POST      => 'is_singular',
            Cache_Tag::ADMIN     => 'is_admin',
            Cache_Tag::AJAX      => 'is_ajax',
        );

        // Compute conditional cache tags
        foreach ( $mapping as $name => $condition ) {
            if ( $this->evaluate_condition( $condition ) ) {
                $this->cache_tags[] = $this->cache_tag_factory->create( $name, $this->get_param( $name ) );
            }
        }

        $this->add_global_cache_tags();
    }

    /**
     * Add all global cache tags that are common for all requests.
     *
     * This includes the following keys:
     * - `{web_property_handle}_{blog_id}`
     * - `{web_property_handle}_{blog_id}_dynamic`
     * - `{host_header}_{blog_id}`
     * - `{host_header}_{blog_id}_dynamic`
     *
     * @return void
     */
    private function add_global_cache_tags(): void {
        $blog_id = WP_Utils::get_blog_id();

        /*
         * Add a cache tag to purge EVERYTHING on a multisite or standalone installation.
         *
         * Format: `{web_property_handle}_{blog_id}`
         * Example: `example_1`
         */
        $this->cache_tags[] = ( $this->cache_tag_factory->create(
            implode( '_', array( $this->web_property_handle, $blog_id ) )
        ) )->do_not_prefix();

        /*
         * Add a cache tag to purge only dynamic content of a multisite or standalone installation.
         * Dynamic content is defined as anything generated by WordPress and processed by our plugin.
         *
         * Format: `{web_property_handle}_{blog_id}_dynamic`
         * Example: `example_1_dynamic`
         */
        $this->cache_tags[] = $this->cache_tag_factory->create( 'dynamic' );

        if ( ! empty( $_SERVER['HTTP_HOST'] ) ) {
            $this->add_domain_cache_tags();
        }
    }

    /**
     * Add cache tags for a specific domain.
     *
     * This includes the following keys:
     * - `{host_header}_{blog_id}`
     * - `{host_header}_{blog_id}_dynamic`
     *
     * @return void
     */
    private function add_domain_cache_tags(): void {
        $blog_id = WP_Utils::get_blog_id();

        /*
         * Add a cache tag to purge EVERYTHING related to a domain
         * of a multisite or standalone installation.
         *
         * Format: `{host_header}_{blog_id}`
         * Example: `example.com_1`
         */
        $this->cache_tags[] = ( $this->cache_tag_factory->create(
            implode( '_', array( $_SERVER['HTTP_HOST'], $blog_id ) )
        ) )->do_not_prefix();

        /*
         * Add a cache tag to purge only dynamic content for a specific domain
         * of a multisite or standalone installation.
         *
         * Format: `{host_header}_{blog_id}_dynamic`
         * Example: `example.com_1_dynamic`
         */
        $this->cache_tags[] = ( $this->cache_tag_factory->create(
            implode( '_', array( $_SERVER['HTTP_HOST'], $blog_id, 'dynamic' ) )
        ) )->do_not_prefix();
    }

    /**
     * Add the cache tag header.
     *
     * @return void
     */
    public function add_cache_tag_header(): void {
        $headers = Headers::get_instance();

        // Construct an array of cache tags containing only the values
        $cache_tags = array_map(
            function ( $cache_tag ) {
                return $cache_tag->get_value();
            },
            $this->cache_tags
        );

        /**
         * Filters the list of cache tags to add to the response.
         *
         * @since 1.1.0
         *
         * @param array $cache_tags The list of cache tags to add.
         */
        $cache_tags = apply_filters( 'pressidium_edge_cache_tags', $cache_tags );

        // Add the `Surrogate-Key` header with a space-separated list of cache tags as its value
        $headers->add_header( self::CACHE_TAG_HEADER, implode( ' ', $cache_tags ) );
    }

    /**
     * Evaluate the given condition.
     *
     * Will call a method of this class with the given name, if it exists.
     * Otherwise, will call a global WordPress function with the given name, if it exists.
     * If neither exists, will return `false`.
     *
     * @param string $condition Condition to evaluate.
     *
     * @return bool
     */
    private function evaluate_condition( string $condition ): bool {
        if ( method_exists( $this, $condition ) ) {
            return $this->$condition();
        }

        if ( function_exists( $condition ) ) {
            return $condition();
        }

        return false;
    }

    /**
     * Return the cache tag parameter, if any.
     *
     * @param string $name Cache tag name.
     *
     * @return ?string Cache tag parameter.
     */
    private function get_param( string $name ): ?string {
        // Mapping of cache tags to parameter methods.
        $mapping = array(
            Cache_Tag::AUTHOR    => 'get_author_id',
            Cache_Tag::TAXONOMY  => 'get_taxonomy_id',
            Cache_Tag::POST_TYPE => 'get_post_type_name',
            Cache_Tag::DATE      => 'get_year',
            Cache_Tag::POST      => 'get_post_id',
        );

        if ( ! isset( $mapping[ $name ] ) ) {
            return null;
        }

        return $this->{$mapping[ $name ]}();
    }

    /**
     * Whether the current request is an archive of any taxonomy.
     *
     * We cannot use `is_tax()` here, because it only works for custom taxonomies.
     * Instead, we need to check if the current request is an archive of any taxonomy,
     * including the default ones (category, tag, etc.).
     *
     * Refer to the following ticket for more information about `is_tax()`:
     *
     * @link https://core.trac.wordpress.org/ticket/18636
     *
     * @return bool
     */
    private function is_any_taxonomy(): bool {
        return is_category() || is_tag() || is_tax();
    }

    /**
     * Whether the current request is a sitemap request.
     *
     * Handles the following cases:
     *
     *  - `/sitemap_index.xml` (used by Yoast)
     *  - `/*-sitemap.xml`     (used by Yoast)
     *  - `/wp-sitemap-*.xml`  (used by WordPress core)
     *
     * @link https://developer.wordpress.org/reference/functions/wp_sitemaps_get_server/
     *
     * @return bool
     */
    private function is_sitemap(): bool {
        if ( ! function_exists( 'wp_sitemaps_get_server' ) ) {
            return false;
        }

        $sitemap_server = wp_sitemaps_get_server();

        if ( ! $sitemap_server->sitemaps_enabled() ) {
            return false;
        }

        return preg_match( '/(?:wp-sitemap.*|sitemap_index|.*-sitemap)\\.xml/', $_SERVER['REQUEST_URI'] ) === 1;
    }

    /**
     * Whether the current request is a REST API request.
     *
     * Based on WooCommerce's `WooCommerce::is_rest_api_request()`.
     *
     * @return bool
     */
    private function is_rest(): bool {
        if ( empty( $_SERVER['REQUEST_URI'] ) ) {
            return false;
        }

        $rest_prefix = trailingslashit( rest_get_url_prefix() );

        return strpos( $_SERVER['REQUEST_URI'], $rest_prefix ) !== false;
    }

    /**
     * Whether the current request is an AJAX request.
     *
     * Alias for `wp_doing_ajax()`.
     *
     * @link https://developer.wordpress.org/reference/functions/wp_doing_ajax/
     *
     * @return bool
     */
    private function is_ajax(): bool {
        return wp_doing_ajax();
    }

    /**
     * Return the author ID.
     *
     * @return ?int
     */
    private function get_author_id(): ?int {
        $queried_object = get_queried_object();

        if ( ! isset( $queried_object->ID ) ) {
            return null;
        }

        return $queried_object->ID;
    }

    /**
     * Return the taxonomy ID.
     *
     * @return ?string
     */
    private function get_taxonomy_id(): ?string {
        $queried_object = get_queried_object();

        if ( ! isset( $queried_object->term_id ) ) {
            return null;
        }

        return $queried_object->term_id;
    }

    /**
     * Return the post type name.
     *
     * @return ?string
     */
    private function get_post_type_name(): ?string {
        $queried_object = get_queried_object();

        if ( ! isset( $queried_object->name ) ) {
            return null;
        }

        return $queried_object->name;
    }

    /**
     * Return the year of a request for a date-based archive.
     *
     * @return ?string
     */
    private function get_year(): ?string {
        $year = get_query_var( 'year' );

        if ( empty( $year ) ) {
            return null;
        }

        return $year;
    }

    /**
     * Return the post ID.
     *
     * @return ?int
     */
    private function get_post_id(): ?int {
        $queried_object = get_queried_object();

        if ( ! isset( $queried_object->ID ) ) {
            return null;
        }

        return $queried_object->ID;
    }

    /**
     * Return all cache tags.
     *
     * @return Cache_Tag[]
     */
    public function get_cache_tags(): array {
        return $this->cache_tags;
    }

}
